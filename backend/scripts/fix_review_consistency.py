"""修正文献综述中 3 处与现行参考文献表/语料策略不一致的表述。

问题来源
--------
先前把参考文献从 15 篇替换为 12 篇时，只重编了正文中的 [n] 编号，
**没有同步更新正文里写死的文献名称与年份**，造成引用编号与引用内容不符。

三处不一致
----------
1. 「1. 背景意义」：正文写《中国结直肠癌诊疗规范（2023版）》[1]，
   而 [1] 现为 2025 版 → 版本年份不符。
2. 「三、技术路线」：正文写「通过程序接口从 PubMed 等数据库批量采集」，
   与「中文为主体、外文为补充」的新语料策略矛盾。
3. 「四、课题的主要内容」：正文写《成人肠外营养脂肪乳注射液临床应用指南
   （2023版）》[5]，而 [5] 现为《机器人结直肠癌手术专家共识（2025版）》
   → **引用编号与引用内容完全不符**，属硬伤。

第 3 处为什么换成肝转移指南
--------------------------
原句的结构是「诊疗纲领 …… 专项规范」，需要一个「针对特定临床问题的专项指南」
作为对例。可选文献中，《结直肠癌肝转移诊断和综合治疗指南（2025版）》[2]
最贴合这一语义（肝转移的处理涉及多学科协作，是典型的专项问题），
且与原句「支持治疗的专项规范」的意图一致。
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

CONTENT = Path(r"D:\AI\RAG_project\backend\scripts\review_content.py")

# (旧片段, 新片段, 说明)
FIXES: list[tuple[str, str, str]] = [
    (
        "在《中国结直肠癌诊疗规范（2023版）》中系统总结",
        "在《中国结直肠癌诊疗规范（2025版）》中系统总结",
        "背景意义：诊疗规范 2023版 → 2025版（与文献[1]一致）",
    ),
    (
        "离线阶段完成知识准备：通过程序接口从 PubMed 等数据库批量采集"
        "结直肠手术围术期相关文献题录与摘要，经格式解析、文本切分与结构化标引后写入知识库；",
        "离线阶段完成知识准备：以中文临床指南与知网收录的中文期刊文献为主体，"
        "经格式解析、文本切分与结构化标引后写入知识库，"
        "同时从 PubMed 采集结直肠手术围术期外文文献题录与摘要作为补充；",
        "技术路线：PubMed 主采集 → 中文主体 + 外文补充",
    ),
    (
        "既包括《中国结直肠癌诊疗规范（2023版）》[1]这类诊疗纲领，"
        "也涵盖《成人肠外营养脂肪乳注射液临床应用指南（2023版）》[5]这类支持治疗的专项规范",
        "既包括《中国结直肠癌诊疗规范（2025版）》[1]这类诊疗纲领，"
        "也涵盖《结直肠癌肝转移诊断和综合治疗指南（2025版）》[2]这类针对特定临床问题的专项指南",
        "研究内容：修正 [5] 的引用内容（原引用与文献表不符）",
    ),
]


def main() -> int:
    t = CONTENT.read_text(encoding="utf-8")
    n_ok = 0
    for old, new, label in FIXES:
        if old in t:
            t = t.replace(old, new, 1)
            print("✓ %s" % label)
            n_ok += 1
        else:
            print("✗ 未找到锚点: %s" % label)

    if n_ok:
        CONTENT.write_text(t, encoding="utf-8")

    # 一致性复核：正文引用的文献名与文献表是否冲突
    body, _, refs_part = t.partition("REFS = [")
    print()
    print("=== 一致性复核 ===")
    ref_titles = dict(re.findall(r'"\[(\d+)\][^"]*?\.\s*([^\.\[]+)\[J\]', refs_part))
    cites = sorted({int(x) for x in re.findall(r"\[(\d+)\]", body)})
    print("  文献表条目: %s" % sorted(int(k) for k in ref_titles))
    print("  正文引用  : %s" % cites)
    # 检查是否残留旧文献名
    stale = ["2023版）[1]", "肠外营养脂肪乳", "从 PubMed 等数据库批量采集"]
    left = [s for s in stale if s in body]
    print("  残留旧表述: %s" % (left if left else "无 ✓"))
    return 0 if n_ok == len(FIXES) else 1


if __name__ == "__main__":
    raise SystemExit(main())
