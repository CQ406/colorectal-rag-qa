def main() -> int:
    if not DOC.exists():
        print("文件不存在: %s" % DOC)
        return 1

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = DOC.with_name(DOC.stem + f".bak_{stamp}" + DOC.suffix)
    shutil.copy2(DOC, backup)
    print("已备份: %s" % backup.name)
    print()

    doc = Document(str(DOC))
    # 研究的主要内容 / 技术路线 / 预期结果 分别位于表 2 的第 3、4、5 行
    target_cells = [doc.tables[1].rows[i].cells[0] for i in (2, 3, 4)]

    n_ok = 0
    for anchor, new_text, label in EDITS:
        hit = False
        for cell in target_cells:
            for para in cell.paragraphs:
                if anchor not in para.text:
                    continue
                if len(para.runs) == 1:
                    para.runs[0].text = new_text
                else:
                    for r in para.runs[1:]:
                        r.text = ""
                    para.runs[0].text = new_text
                print("✓ %s" % label)
                print("   %s…" % new_text[:64])
                hit = True
                n_ok += 1
                break
            if hit:
                break
        if not hit:
            print("✗ 未找到锚点: %s" % anchor[:30])

    if n_ok == 0:
        print("\n未做修改，文件未写入")
        return 1

    doc.save(str(DOC))
    print()
    print("已保存: %s（修改 %d 处）" % (DOC.name, n_ok))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
