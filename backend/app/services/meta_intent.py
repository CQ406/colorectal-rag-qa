"""识别「助手指令 / 自我身份」类问题，避免把它们当成知识提问去检索。

为什么需要
----------
`classify_intent` 只区分知识提问、决策建议、比较、总结四类。
用户问「你是谁」「你能做什么」时，会被判成 **知识提问（置信度极低，约 0.1）**，
于是走了完整的检索 + 生成链路，最后答出：

    提供的资料中未包含与"我是谁"或助手身份设定相关的信息，因此无法依据证据片段回答…

这不是系统故障，而是**意图识别缺了一类**：这类问题不需要检索，
应当直接以系统自身身份回答，并顺带说明能力边界与提问方式。
"""
from __future__ import annotations

import re

# 身份询问
_IDENTITY = [
    r"你是谁", r"你叫什么", r"你的名字", r"你是什么(东西|系统|模型|ai|机器人)?",
    r"你是(机器人|ai|人工智能|大模型|程序)", r"你从(哪|哪里)来",
]
# 能力询问
_ABILITY = [
    r"你能(做|干)(什么|啥)", r"你会(做|干)?什么", r"你有什么(功能|能力|用)",
    r"能帮我(做|干)(什么|啥)", r"可以(做|帮)(什么|啥)", r"你的功能",
    r"你能干(什么|啥)", r"你会什么",
]
# 使用方式
_USAGE = [
    r"怎么用", r"如何使用", r"使用(说明|方法|指南)", r"^(帮助|help|使用帮助)$",
    r"怎么(提问|问)", r"如何提问",
]
# 边界类（能不能替代医生 / 能不能诊断）
_BOUNDARY = [
    r"你能(替代|代替|取代)医生", r"你能(诊断|看病|开药)", r"你的(结论|回答)可靠",
]

_PATTERNS = [re.compile(p, re.I) for p in (_IDENTITY + _ABILITY + _USAGE + _BOUNDARY)]

# 过长的提问通常包含具体临床内容，不当作单纯的身份询问
_MAX_LEN = 30


def is_meta_question(question: str) -> bool:
    """判断是否为无需检索的「助手指令/身份/用法」类问题。"""
    t = re.sub(r"[\s，。？?！!、,]+", "", question or "")
    if not t or len(t) > _MAX_LEN:
        return False
    return any(p.search(t) for p in _PATTERNS)


def build_meta_answer(doc_count: int | None = None, chunk_count: int | None = None) -> str:
    """构造自我介绍式回答（不检索、不带引用）。

    刻意写清三件事：能做什么、不能做什么、怎么问更好。
    医学场景下「不能做什么」比「能做什么」更重要 —— 避免用户误以为可替代医师。
    """
    scope = "结直肠手术围术期"
    scale = ""
    if doc_count and chunk_count:
        scale = f"\n\n当前知识库收录 {doc_count} 篇文献、{chunk_count} 个文本块，以中文指南与期刊全文为主体。"
    elif doc_count:
        scale = f"\n\n当前知识库收录 {doc_count} 篇文献，以中文指南与期刊全文为主体。"

    return (
        f"我是{scope}多模态知识库的智能问答助手，用于**教学与科研**场景。{scale}\n\n"
        "**我能做什么**\n"
        "- 回答结直肠手术围术期（术前评估、术中决策、术后并发症与康复）的循证问题；\n"
        "- 每个结论都标注来源文献，可点击查看原文片段与证据等级；\n"
        "- 支持连续追问，会自动把你的指代还原成完整问题；\n"
        "- 支持上传术中影像，给出客观描述并结合文献给出辅助解读。\n\n"
        "**我不能做什么**\n"
        "- **不构成诊疗建议**，不能替代医师的临床判断；\n"
        "- 只依据知识库中的文献作答，库中没有的内容我会明确说明「资料不足」，"
        "不会凭记忆编造。\n\n"
        "**怎么问更好**\n"
        "尽量给出具体临床问题，例如：\n"
        "- 术中如何评估肠道吻合口的血供？\n"
        "- 直肠癌新辅助治疗后完全缓解可以局部切除吗？\n"
        "- 加速康复外科的核心措施有哪些？"
    )
