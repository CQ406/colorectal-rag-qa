import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, role: 'admin' | 'physician') {
  const response = await page.request.post('/api/auth/login', {
    data: { username: `e2e-${role}`, password: 'E2eOnly!234' },
  })
  expect(response.ok()).toBeTruthy()
  const data = await response.json()
  await page.addInitScript(({ token, user }) => {
    localStorage.setItem('cr_access_token', token)
    localStorage.setItem('cr_user', JSON.stringify(user))
  }, { token: data.access_token, user: data.user })
}

