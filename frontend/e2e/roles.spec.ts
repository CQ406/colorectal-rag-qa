test('durable chat restores after reload and isolates visitors and authenticated accounts', async ({ page, browser }) => {
  await page.goto('/chat')
  await page.getByPlaceholder('输入临床问题…（Enter 发送，Shift+Enter 换行）').fill('你是谁')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.msg-row.assistant .bubble')).toBeVisible()
  const guestId = await page.evaluate(() => localStorage.getItem('cr.chat.session_id.guest'))
  expect(guestId).toBeTruthy()
  await page.reload()
  await expect(page.locator('.msg-row.user .bubble')).toHaveText('你是谁')
  await expect(page.locator('.msg-row.assistant .bubble')).toBeVisible()
  const stranger = await browser.newContext()
  expect((await stranger.request.get(`http://127.0.0.1:5174/api/chat/${guestId}`)).status()).toBe(404)
  expect((await stranger.request.post('http://127.0.0.1:5174/api/chat/stream', { data: { question: '你是谁', session_id: guestId } })).status()).toBe(404)
  await stranger.close()
  const adminAuth = await page.request.post('/api/auth/login', { data: { username:'e2e-admin',password:'E2eOnly!234' } })
  const adminData = await adminAuth.json()
  await page.evaluate(({token,user}) => { localStorage.setItem('cr_access_token',token); localStorage.setItem('cr_user',JSON.stringify(user)) },{token:adminData.access_token,user:adminData.user})
  await page.reload()
  await expect(page.locator('.msg-row')).toHaveCount(0)
  await page.getByPlaceholder('输入临床问题…（Enter 发送，Shift+Enter 换行）').fill('你能做什么')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.msg-row.assistant .bubble')).toBeVisible()
  const adminId = await page.evaluate(id => localStorage.getItem(`cr.chat.session_id.${id}`), adminData.user.id)
  expect(adminId).toBeTruthy()
  const physician = await page.request.post('/api/auth/login',{data:{username:'e2e-physician',password:'E2eOnly!234'}})
  const physicianData = await physician.json()
  expect((await page.request.get(`/api/chat/${adminId}`,{headers:{Authorization:`Bearer ${physicianData.access_token}`}})).status()).toBe(404)
  await page.goto('/admin')
  await page.getByRole('button',{name:'退出',exact:true}).click()
  await page.goto('/chat')
  await expect(page.locator('.msg-row.user .bubble')).toHaveText('你是谁')
  await expect(page.locator('.chat-column')).not.toContainText('你能做什么')
})

test('logout while viewing a private case clears draft content and review records', async ({ page }) => {
  await login(page, 'physician')
  await page.goto('/cases')
  const row=page.getByRole('row').filter({hasText:'E2E-DRAFT'})
  await expect(row).toBeVisible()
  await row.getByRole('button',{name:'E2E synthetic draft',exact:true}).click()
  await expect(page.locator('.el-dialog')).toBeVisible()
  // Exercise the same store transition used by the logout button without
  // unmounting the case page, so stale private content cannot hide on navigation.
  await page.evaluate(async () => {
    const module = await import('/src/stores/auth.ts')
    module.useAuthStore().logout()
  })
  await expect(page.locator('.el-dialog')).not.toBeVisible()
  await expect(page.getByRole('row').filter({hasText:'E2E-DRAFT'})).toHaveCount(0)
})

