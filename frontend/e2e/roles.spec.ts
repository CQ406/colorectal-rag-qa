test('image details ignore an older response that arrives after switching images', async ({ page }) => {
  await page.goto('/images')
  await expect(page.locator('.card')).toHaveCount(24)
  await page.route(/\/api\/images\/[a-f0-9-]{36}$/, async route => {
    const response = await route.fetch()
    const data = await response.json()
    if (data.title === 'E2E image 24') await new Promise(resolve => setTimeout(resolve, 900))
    data.vlm_analysis = `Description for ${data.title}`
    await route.fulfill({ response, json: data })
  })
  await page.locator('.card').nth(0).click()
  await page.locator('.card').nth(1).click()
  await expect(page.locator('.detail-title')).toHaveText('E2E image 23')
  await expect(page.locator('.detail-pane')).toContainText('Description for E2E image 23')
  await page.waitForTimeout(1100)
  await expect(page.locator('.detail-pane')).not.toContainText('Description for E2E image 24')
})

